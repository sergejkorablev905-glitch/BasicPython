def get_results(prices):
    # Считаем общую сумму
    total = sum(prices)
    # Находим максимальную цену
    my_max = max(prices)
    # Находим минимальную цену
    my_min = min(prices)
    # Возвращаем сразу три результата
    return total, my_max, my_min
