# 6. Точка в круге
######################
# Даны координаты точки, координаты центра круга и его радиус.
# Определить принадлежит ли данная точка кругу.
#
# Будем считать, что точка принадлежит кругу, если находится внутри его или на его окружности
#
# Формат входных данных
# Даны координаты точки (x, y) - два целых числа, каждое на отдельной строке
# Координаты центра круга (xr, yr) - два целых числа, каждое на отдельной строке
# Радиус круга - целое положительное число.
#
# Формат выходных данных
# Вывести "Да", если точка принадлежит кругу, и "Нет" в противоположном случае.
# РЕШЕНИЕ:
# Считываем координату x проверяемой точки.
# int() превращает введённое значение в целое число.
x = int(input())
# Считываем координату y проверяемой точки.
y = int(input())
# Считываем координату x центра круга.
# xr — это координата x центра круга.
xr = int(input())
# Считываем координату y центра круга.
# yr — это координата y центра круга.
yr = int(input())
# Считываем радиус круга.
# r — это расстояние от центра круга до его границы.
r = int(input())
# Проверяем, находится ли точка внутри круга
# или непосредственно на его границе.
#
# (x - xr) — разница между координатой x точки
# и координатой x центра круга.
#
# (y - yr) — разница между координатой y точки
# и координатой y центра круга.
#
# ** 2 — возводим каждую разницу в квадрат.
# Это нужно для применения формулы расстояния.
#
# Слева получаем квадрат расстояния
# от точки до центра круга.
#
# r ** 2 — квадрат радиуса круга.
#
# Если квадрат расстояния меньше или равен
# квадрату радиуса, значит точка находится
# внутри круга или на его границе.
#
# <= означает "меньше или равно".
if (x - xr) ** 2 + (y - yr) ** 2 <= r ** 2:

    # Если условие выполнилось,
    # значит точка находится внутри круга
    # или на его границе.
    print("Да")

# Если условие выше не выполнилось,
# значит точка находится за пределами круга.
else:

    # Выводим "Нет".
    print("Нет")
