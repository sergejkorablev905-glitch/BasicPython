# 3. Поиск победителя голосования
# ################################
# Задача
# Даны результаты голосования. С клавиатуры вводится количество записей N
# , а затем N строк, каждая из которых содержит имя кандидата и количество отданных за него голосов (через пробел).
# Напишите программу, которая считывает эти данные в словарь, определяет кандидата с наибольшим количеством голосов и выводит его имя и набранные баллы.
# Если победителей несколько, выведите любого из них.
# Входные данные
# В первой строке — целое число N(N≥1).
# В следующих N строках — имя кандидата (одно слово) и целое число голосов, разделенные пробелом
# Выходные данные
# Имя победителя и количество голосов через пробел.
# РЕШЕНИЕ:
# Считываем количество строк с результатами голосования
# Например, если n = 5,
# значит ниже мы введём 5 строк
n = int(input())
# Создаём пустой словарь
# Здесь будем хранить:
# имя → количество голосов
# Например:
# {
#     "Анна": 15,
#     "Иван": 20
# }
voting = {}
# Повторяем цикл n раз
# То есть считываем n результатов голосования
for i in range(n):
    # Считываем одну строку
    # split() разделяет её на части по пробелу
    # Например:
    # "Анна 10"
    # превращается в:
    # ["Анна", "10"]
    data = input().split()
    # Берём первый элемент списка
    # Это имя кандидата
    # data[0] → "Анна"
    name = data[0]
    # Берём второй элемент списка
    # Это количество голосов
    # data[1] → "10"
    # int() превращает "10" из строки в число 10
    votes = int(data[1])
    # Проверяем, есть ли имя кандидата
    # уже в словаре
    if name not in voting:
        # Если кандидата ещё нет,
        # создаём его в словаре
        # и начинаем его счёт с 0 голосов
        voting[name] = 0
    # Добавляем новые голоса
    # к уже накопленному количеству
    # Например:
    # было 10 голосов
    # пришло ещё 5
    # станет:
    # 10 + 5 = 15
    voting[name] = voting[name] + votes
# Создаём переменную для имени победителя
# Пока победитель неизвестен,
# поэтому записываем пустую строку
winner = ""
# Создаём переменную для максимального количества голосов
# Пока мы ещё никого не проверили,
# максимальное количество голосов равно 0
max_votes = 0
# Перебираем все пары из словаря
# key — имя кандидата
# value — количество его голосов
for key, value in voting.items():
    # Проверяем:
    # количество голосов текущего кандидата
    # больше ли уже найденного максимума?
    if value > max_votes:
        # Если да,
        # запоминаем новое максимальное количество голосов
        max_votes = value
        # И запоминаем имя этого кандидата
        winner = key
# Выводим имя победителя
# и количество набранных им голосов
print(winner, max_votes)
