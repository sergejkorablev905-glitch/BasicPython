# Описание алгоритма RLE(run-length encoding)
# Кодирование длин серий (RLE) — это простая форма сжатия данных без потерь,
# которая выполняется для последовательностей с одним и тем же значением,
# повторяющимся много раз подряд.
# Он кодирует последовательность для хранения только одного значения и его количества.
# Например, рассмотрим строку:
# aaaabbcccccccddddgggggggggggg
# С помощью алгоритма RLE, ее можно сжать в такую:
# 4a2b7c4d12g
# Т.е. мы просто считаем количество одинаковых символов подряд и вместо aaaa -> 4a
# Задание
# Дана непустая строка символов. Напишите функцию, кодирующую данную строку алгоритмом RLE.
# Формат входных данных
# Дана произвольная строка символов.
# Формат выходных данных
# Написать функцию кодирования исходной строки.
# РЕШЕНИЕ:
def rle_encode(s):
    # Создаём функцию rle_encode.
    # s — это строка, которую мы хотим закодировать.
    # Например:
    # s = "aaabbc"
    if not s:
        # Проверяем, пустая ли строка.
        # not s означает:
        # "если строка пустая".
        # Пустая строка выглядит так:
        # s = ""
        return ""
        # Если строка пустая, сразу возвращаем пустую строку.
        # Дальше код выполнять не нужно.
    prev_char = s[0]
    # Берём первый символ строки.
    # s[0] — первый символ.
    # Например:
    # s = "aaabbc"
    # s[0] = "a"
    # prev_char означает "предыдущий символ".
    count = 1
    # Считаем первый символ.
    # Пока мы нашли только одну букву "a",
    # поэтому количество равно 1.
    result = ""
    # Создаём пустую строку result.
    # В неё постепенно будем записывать результат.
    for cur_char in s[1:]:
        # Перебираем все символы строки, начиная со второго.
        # s[1:] означает:
        # "взять строку начиная с индекса 1 до конца".
        # Например:
        # s = "aaabbc"
        # s[1:] = "aabbc"
        # cur_char — текущий символ.
        if prev_char != cur_char:
            # Проверяем:
            # предыдущий символ НЕ равен текущему?
            # != означает "не равно".
            # Если символ изменился,
            # значит группа одинаковых символов закончилась.
            result = result + str(count) + prev_char
            # Добавляем готовую группу в результат.
            # str(count) превращает число в строку.
            # Например:
            # count = 3
            # prev_char = "a"
            # str(count) + prev_char
            # "3" + "a"
            # "3a"
            # result получает "3a".
            prev_char = cur_char
            # Теперь текущий символ становится предыдущим.
            # Например:
            # было:
            # prev_char = "a"
            # cur_char = "b"
            # становится:
            # prev_char = "b"
            count = 1
            # Начинаем считать новую группу.
            # Новый символ мы встретили один раз.
        else:
            # Если prev_char и cur_char одинаковые,
            # значит продолжается группа одинаковых символов.
            count += 1
            # Увеличиваем количество одинаковых символов на 1.
            # То же самое, что:
            # count = count + 1
    result = result + str(count) + prev_char
    # После окончания цикла последняя группа
    # ещё не была добавлена в result.
    # Поэтому добавляем её здесь.
    # Например:
    # count = 2
    # prev_char = "c"
    # добавится:
    # "2c"
    return result
    # Возвращаем полностью готовую строку.
