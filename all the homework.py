# Считываем длину первой стороны треугольника.
# input() получает значение с клавиатуры,
# а int() превращает его в целое число.
a = int(input())
# Считываем длину второй стороны треугольника.
b = int(input())
# Считываем длину третьей стороны треугольника.
c = int(input())
# Находим полупериметр треугольника.
# Сначала складываем все три стороны:
# a + b + c
# Затем делим полученную сумму на 2.
# Формула полупериметра:
# p = (a + b + c) / 2
p = (a + b + c) / 2
# Находим площадь треугольника по формуле Герона.
# Формула Герона:
# S = √(p * (p - a) * (p - b) * (p - c))
# В Python квадратный корень записан как возведение
# в степень 0.5.
# Поэтому:
# (...) ** 0.5
# означает "извлечь квадратный корень".
S = (p * (p - a) * (p - b) * (p - c)) ** 0.5
# Складываем три стороны и получаем периметр.
# Периметр треугольника = a + b + c.
# print() выводит полученное значение на экран.
print(a + b + c)
# Выводим площадь треугольника.
#
# f перед строкой позволяет вставить значение переменной S
# прямо внутрь текста.
#
# :.2f означает:
# вывести число с 2 знаками после запятой.
#
# Например:
# 6 → 6.00
# 6.5 → 6.50
# 6.666 → 6.67
print(f"{S:.2f}")
