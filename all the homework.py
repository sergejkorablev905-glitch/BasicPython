# Задание
# Напишите функцию is_strong_password(password),
# которая проверяет надёжность переданного пароля на соответствие критериям безопасности.
# Пароль считается надёжным, если он одновременно удовлетворяет следующим условиям:
#     1.Длина строки составляет не менее 8 символов.
#     2.Содержит хотя бы одну заглавную латинскую или русскую букву.
#     3.Содержит хотя бы одну строчную латинскую или русскую букву.
#     4.Содержит хотя бы одну цифру (0–9).
# Формат входных данных
# Функция принимает один параметр password — строку (str), содержащую проверяемый пароль.
# Строка может состоять из латинских и русских букв, цифр и специальных символов.
#
# Формат выходных данных
# Функция должна возвращать булево значение (bool):
#   True — если пароль соответствует всем четырем критериям надёжности.
#   False — если пароль не соответствует хотя бы одному из критериев.
# Примеры
# Пример 1:
# Входные данные: is_strong_password("Pass1234")
# Выходные данные: True
# Пример 2:
# Входные данные: is_strong_password("password")
# Выходные данные: False (отсутствуют заглавные буквы и цифры)
#------------------------------------------
# Шаг 1. Создаём функцию
def is_strong_password(password):
    # Разбираем:
    # def — говорим Python: «сейчас я создаю функцию».
    # is_strong_password — имя нашей функции.
    # password — параметр, то есть сюда функция получит пароль.
    # : — после двоеточия начинается тело функции.
    if len(password) < 8:
        # len(password) считает количество символов в пароле.
        # Если символов не меньше 8, условие выполняется.
        return False
        # Возвращаем False — пароль ненадёжный.
        # Функция сразу заканчивает работу.
    has_upper = False      # Фраза has_upper переводится с английского как  (верхний регистр)».
    # Создаём переменную-флажок.
    # False означает: пока заглавную букву не нашли.
    has_lower = False      # Фраза has_upper переводится с английского как  (нижний регистр)».
    # Создаём флажок для строчной буквы.
    # Пока строчную букву не нашли → False.
    has_digit = False     # Фраза has_upper переводится с английского как  (содержит цифру)».
    # Создаём флажок для цифры.
    # Пока цифру не нашли → False.
    for char in password:
        # Берём каждый символ пароля по очереди.
        # char — текущий символ.
        if char.isupper():
            # Проверяем: является ли текущий символ заглавной буквой?
            has_upper = True
            # Если заглавная буква найдена,
            # меняем флажок на True.
        if char.islower():
            # Проверяем: является ли текущий символ строчной буквой?
            has_lower = True
            # Если строчная буква найдена,
            # меняем флажок на True.
        if char.isdigit():
            # Проверяем: является ли текущий символ цифрой?
            has_digit = True
            # Если цифра найдена,
            # меняем флажок на True.
    if has_upper and has_lower and has_digit:
        # Проверяем сразу три условия:
        # есть заглавная И строчная И цифра.
        return True
        # Все три условия выполнены.
        # Возвращаем True — пароль надёжный.

    return False
    # Если хотя бы одного условия нет,
    # возвращаем False — пароль ненадёжный.

