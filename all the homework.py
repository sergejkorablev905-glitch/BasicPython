# 3. Шоколадка
# ######################
# Задание
# Требуется определить, можно ли от шоколадки размером n × m долек отломить k долек , если разрешается сделать один разлом по прямой между дольками (то есть разломить шоколадку на два прямоугольника)
# Формат входных данных
# Вводятся 3 целых положительных числа n, m и k (каждое на отдельной строке). Точно известно, что k ≠ n ⋅ m.
# Формат выходных данных
# Выведите "Да", если можно отломить от шоколадки ровно k долек, и "Нет" если нельзя.
# РЕШЕНИЕ:
# Считываем количество рядов шоколадки.
# int() превращает введённое значение в целое число.
n = int(input())
# Считываем количество столбцов шоколадки.
# m — это вторая сторона шоколадки.
m = int(input())
# Считываем, сколько кусочков шоколадки хотим получить.
# k — нужное количество клеток.
k = int(input())
# Проверяем сразу несколько условий.
# k < n * m
# означает, что нам нужно меньше клеток,
# чем всего есть в шоколадке.
# n * m — общее количество клеток шоколадки.
# Например:
# n = 3
# m = 4
# всего клеток:
# 3 * 4 = 12
#
# Поэтому k должно быть меньше 12.
# k % n == 0
# проверяет, делится ли k на количество рядов без остатка.
#
# Это означает, что можно отломить часть шоколадки
# по одному направлению.
# k % m == 0
# проверяет, делится ли k на количество столбцов без остатка.
#
# Это означает, что можно отломить часть шоколадки
# по другому направлению.
# or означает "ИЛИ".
# Нам достаточно, чтобы выполнялось хотя бы одно
# из двух условий:
# k делится на n ИЛИ k делится на m.
# and означает "И".
# Поэтому одновременно должны выполняться:
# 1. k меньше общего количества клеток
# 2. k делится на n или на m
if k < n * m and (k % n == 0 or k % m == 0):
    # Если все необходимые условия выполнены,
    # значит можно получить k клеток одним разломом.
    print("Да")
# Если хотя бы одно необходимое условие
# не выполнено, выполняется else.
else:
    # Выводим "Нет",
    # потому что получить k клеток одним разломом нельзя.
    print("Нет")
