# 4. Статистика слова
############################
# Задание
# Напишите функцию get_word_stats(word), которая принимает в качестве аргумента одно слово и анализирует его состав.
# Функция должна определять длину слова, количество гласных и количество согласных букв.
#
# В подсчете гласных и согласных букв участвуют только буквы русского алфавита (как строчные, так и заглавные). Буква «ё» считается гласной.
# Подсчет должен быть регистронезависимым.
#
# Формат входных данных
# Функция принимает один параметр word — строку (str), состоящую из одного слова без пробелов и знаков препинания (буквы русского алфавита).
#
# Формат выходных данных
# Функция должна возвращать кортеж (tuple) из трех целых чисел в следующем порядке:
# 1. Длина слова.
# 2. Количество гласных букв (а, е, ё, и, о, у, ы, э, ю, я).
# 3. Количество согласных букв (б, в, г, д, ж, з, й, к, л, м, н, п, р, с, т, ф, х, ц, ч, ш, щ).
#
# Пример 1:
# Входные данные: get_word_stats("Питон")
# Результат функции: (5, 2, 3)
#
# Пример 2:
# Входные данные: get_word_stats("Экзамен")
# Результат функции: (7, 3, 4)


# Решение
# Создаём функцию с именем get_word_stats.
# Функция будет получать одно слово.
# word — это название переменной, в которую попадёт переданное слово.
def get_word_stats(word):

    # Приводим всё слово к нижнему регистру.
    # Это нужно для того, чтобы программа одинаково обрабатывала
    # заглавные и строчные буквы.
    # Например:
    # "моЛь" → "моль"
    # "ПИТОН" → "питон"
    word = word.lower()

    # С помощью len() узнаём длину слова.
    # len означает "length" — длина.
    # Например:
    # len("моль") → 4
    count = len(word)

    # Создаём счётчик гласных букв.
    # В начале мы ещё не встретили ни одной буквы,
    # поэтому значение равно 0.
    vowels = 0

    # Создаём счётчик согласных букв.
    # В начале согласных тоже ещё нет,
    # поэтому значение равно 0.
    consonants = 0

    # Начинаем перебирать слово буква за буквой.
    # c — это переменная, в которой по очереди будет находиться
    # каждая буква слова.
    # Например, для слова "моль":
    # сначала c = "м"
    # потом c = "о"
    # потом c = "л"
    # потом c = "ь"
    for c in word:

        # Проверяем, есть ли текущая буква среди русских гласных.
        # "in" означает "находится внутри".
        # Например:
        # "о" in "аеёиоуыэюя" → True
        # А:
        # "м" in "аеёиоуыэюя" → False
        if c in 'аеёиоуыэюя':

            # Если буква является гласной,
            # увеличиваем счётчик гласных на 1.
            # Например:
            # было vowels = 0
            # встретили "о"
            # стало vowels = 1
            vowels += 1

        # Если буква не является гласной,
        # проверяем отдельно, является ли она согласной.
        #
        # Это важно, потому что "ь" и "ъ" не являются
        # ни гласными, ни согласными.
        elif c in 'бвгджзйклмнпрстфхцчшщ':

            # Если буква является согласной,
            # увеличиваем счётчик согласных на 1.
            consonants += 1

    # Когда цикл закончил проверять все буквы,
    # возвращаем сразу три результата.
    #
    # Первый результат — длина слова.
    # Второй результат — количество гласных.
    # Третий результат — количество согласных.
    #
    # Для слова "моль" получится:
    # (4, 1, 2)
    return (count, vowels, consonants)

# Вызываем нашу функцию.
# Передаём ей слово "моЛь".
# Функция обработает слово и вернёт:
# (4, 1, 2)
# print() выводит полученный результат на экран.
print(get_word_stats("моЛь"))
