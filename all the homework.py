# 1. Обычный цикл

# Открываем файл sold.txt для чтения
with open("sold.txt", "r", encoding="utf-8") as f:

    # Читаем всё содержимое файла и сохраняем его в переменную text
    text = f.read()

# Разделяем весь текст на отдельные значения
# float превращает каждое значение из текста в число
# list собирает все полученные числа в список prices
prices = list(map(float, text.split()))

# Создаём переменную для общей суммы
# В начале сумма равна 0
total = 0

# Берём первую цену как начальное значение максимальной цены
my_max = prices[0]

# Берём первую цену как начальное значение минимальной цены
my_min = prices[0]

# По очереди берём каждую цену из списка prices
# Текущая цена будет храниться в переменной price
for price in prices:
    # Добавляем текущую цену к общей сумме
    total = total + price
    # Проверяем: текущая цена больше нашего максимума?
    if price > my_max:
        # Если да, записываем текущую цену как новый максимум
        my_max = price
    # Проверяем: текущая цена меньше нашего минимума?
    if price < my_min:
        # Если да, записываем текущую цену как новый минимум
        my_min = price

# Выводим общую сумму
# :.2f означает: показать число с двумя знаками после точки
print(f"{total:.2f}")
# Выводим цену самого дорогого товара
# :.2f — два знака после точки
print(f"{my_max:.2f}")
# Выводим цену самого дешёвого товара
# :.2f — два знака после точки
print(f"{my_min:.2f}")
