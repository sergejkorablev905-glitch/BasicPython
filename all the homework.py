# Получаем первое слово.
# input() — считывает слово с клавиатуры.
# lower() — переводит все буквы в нижний регистр.
# Например:
# "Море" → "море"
word1 = input().lower()
# Получаем второе слово
# и также переводим его в нижний регистр.
# Например:
# "ОМЕР" → "омер"
word2 = input().lower()
