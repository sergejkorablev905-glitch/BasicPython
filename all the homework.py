# r перед строкой означает "сырая строка" (raw string).
# Это удобно при работе с регулярными выражениями.
# [А-Яа-яA-Za-z]
# означает: одна русская или английская буква
# +
# означает: таких букв должно быть ОДНА или БОЛЬШЕ.
# Поэтому:
# "Привет"     -> подходит
# "Hello"      -> подходит
# "123"        -> не подходит
# (?: ... )
# означает группу в регулярном выражении,
# которая нужна для объединения нескольких частей,
# но сама группа отдельно не запоминается.
# -
# обычный дефис.
# [А-Яа-яA-Za-z]+
# снова одна или несколько русских/английских букв.
# ?
# означает, что вся часть
# (дефис + вторая часть слова)
# является необязательной.
# Поэтому подходят:
# "Привет"
# "Hello"
# "Анна-Мария"
# "Ростов-на-Дону" будет найден как "Ростов-на-Дону"
# В итоге весь шаблон ищет:
# обычные слова и слова, состоящие из двух частей через дефис.
